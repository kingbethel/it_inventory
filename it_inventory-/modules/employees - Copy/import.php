$errors = [];
$imported_count = 0;
$updated_count = 0;

// 2. Process CSV Upload
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!verify_csrf_token($_POST['csrf_token'] ?? '')) {
        $errors[] = "Security check failed. Please refresh.";
    } else {
        if (!isset($_FILES['csv_file']) || $_FILES['csv_file']['error'] !== UPLOAD_ERR_OK) {
            $errors[] = "Please select a valid CSV file to upload.";
        } else {
            $file = $_FILES['csv_file'];
            $file_ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));

            if ($file_ext !== 'csv') {
                $errors[] = "Invalid file type. Please upload a standard comma-delimited (.csv) file.";
            } else {
                $handle = fopen($file['tmp_name'], 'r');
                if ($handle === false) {
                    $errors[] = "Unable to read the uploaded CSV file.";
                } else {
                    // Check and strip UTF-8 BOM if generated by Excel
                    $bom = fread($handle, 3);
                    if ($bom !== "\xEF\xBB\xBF") {
                        rewind($handle);
                    }

                    // Read Header Row
                    $header = fgetcsv($handle);

                    $pdo->beginTransaction();
                    $line_number = 1;

                    try {
                        $stmt = $pdo->prepare("
                            INSERT INTO employees (employee_id, first_name, last_name, department, position, employment_status)
                            VALUES (:emp_id, :fname, :lname, :dept, :pos, :status)
                            ON DUPLICATE KEY UPDATE 
                                first_name = VALUES(first_name),
                                last_name = VALUES(last_name),
                                department = VALUES(department),
                                position = VALUES(position),
                                employment_status = VALUES(employment_status)
                        ");

                        while (($row = fgetcsv($handle, 1000, ",")) !== false) {
                            $line_number++;

                            // Skip empty lines
                            if (empty(array_filter($row))) {
                                continue;
                            }

                            $emp_id  = trim($row[0] ?? '');
                            $fname   = trim($row[1] ?? '');
                            $lname   = trim($row[2] ?? '');
                            $dept    = trim($row[3] ?? '');
                            $pos     = trim($row[4] ?? '');
                            $status  = trim($row[5] ?? 'Active');

                            // Basic validation for required columns
                            if (empty($emp_id) || empty($fname) || empty($lname) || empty($dept)) {
                                continue; // Skip incomplete row
                            }

                            if (!in_array($status, ['Active', 'Resigned', 'Terminated'])) {
                                $status = 'Active';
                            }

                            $stmt->execute([
                                ':emp_id' => $emp_id,
                                ':fname'  => $fname,
                                ':lname'  => $lname,
                                ':dept'   => $dept,
                                ':pos'    => $pos,
                                ':status' => $status
                            ]);

                            // Check if inserted or updated
                            if ($stmt->rowCount() == 1) {
                                $imported_count++;
                            } elseif ($stmt->rowCount() == 2) {
                                $updated_count++;
                            }
                        }

                        $pdo->commit();
                        fclose($handle);

                        log_activity($pdo, $_SESSION['user_id'], 'BULK_IMPORT_EMPLOYEES', 'Employee', null, "Imported {$imported_count} new employees, updated {$updated_count} existing via CSV.");

                        set_flash('success', "Bulk Import Complete: <strong>{$imported_count}</strong> employees added, <strong>{$updated_count}</strong> records updated.");
                        redirect('modules/employees/index.php');
                    } catch (Exception $e) {
                        $pdo->rollBack();
                        fclose($handle);
                        $errors[] = "Error on line {$line_number}: " . $e->getMessage();
                    }
                }
            }
        }
    }
}

